"""On-policy rollout storage and GAE computation.

PPO/MAPPO trains from recent trajectories generated by the current policy.  It
is therefore useful to keep this buffer concept separate from the optimizer: in
a larger system this becomes the natural messaging boundary between simulation
rollout services and training services.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from .config import Config


@dataclass
class RolloutBuffer:
    config:         Config
    observations:   list[np.ndarray] = field(default_factory=list)
    global_states:  list[np.ndarray] = field(default_factory=list)
    actions:        list[np.ndarray] = field(default_factory=list)
    log_probs:      list[np.ndarray] = field(default_factory=list)
    rewards:        list[np.ndarray] = field(default_factory=list)
    values:         list[np.ndarray] = field(default_factory=list)
    masks:          list[float]      = field(default_factory=list)

    def add(
        self,
        observations: np.ndarray,
        global_state: np.ndarray,
        actions:      list[int],
        log_probs:    list[float],
        rewards:      np.ndarray,
        values:       np.ndarray,
        done:         bool,
    ) -> None:
        """Store one environment timestep for all agents."""

        ############################################################################
        ### Snapshot array inputs so later environment updates cannot alter history.
        ############################################################################

        # observations: one local view per agent before acting, shaped [num_agents, 4].
        # Each row contains that agent's normalized (row, column) and the target's.
        self.observations.append(np.asarray(observations, dtype=np.float32).copy())

        # global_state: one pre-action vector containing every agent's normalized
        # position, then the target's; the centralized critic sees this full picture.
        self.global_states.append(np.asarray(global_state, dtype=np.float32).copy())

        # actions: one sampled movement index per agent for this timestep:
        # 0 = up, 1 = down, 2 = left, 3 = right, 4 = stay.
        self.actions.append(np.asarray(actions, dtype=np.int64))

        # log_probs: the natural log of each selected action's probability under
        # the policy that sampled it; PPO later compares against these saved scores.
        self.log_probs.append(np.asarray(log_probs, dtype=np.float32))

        # rewards: the immediate reward each agent received after these actions,
        # rather than its accumulated episode score or an estimate of future rewards.
        self.rewards.append(np.asarray(rewards, dtype=np.float32).copy())

        # values: the critic's estimate of each agent's discounted future return
        # from the pre-action global state; GAE uses these predictions as baselines.
        self.values.append(np.asarray(values, dtype=np.float32).copy())
        
        # A terminal transition must not inherit value from the next state.
        self.masks.append(0.0 if done else 1.0)

    def set_terminal_team_reward(self, score: float) -> None:
        """Replace a completed finite episode's rewards with one shared terminal score.

        Args:
            score: Learned outcome reward received by every agent at the final step.

        The buffer must already contain the episode. Intermediate rewards become
        zero, and the final mask prevents bootstrapping beyond success or timeout.
        Previously recorded critic estimates remain the GAE baselines.
        """

        for rewards in self.rewards:
            rewards.fill(0.0)
        self.rewards[-1].fill(score)
        self.masks[-1] = 0.0

    def compute_gae(self, last_values: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Compute GAE independently along time for every agent.

        The original example flattened agents into a single list before GAE,
        which incorrectly treated ``agent 2 at time t`` as the temporal successor
        of ``agent 1 at time t``.  Keeping arrays shaped [time, agent] preserves
        the real temporal dimension.
        """
        
        # store rewards and values into arrays indexed by timestep (T) and agent (N) for vectorized GAE computation.
        # rewards are calculated in environment.py (GridWorldEnv.step) and
        # values are calculated in policy.py (MAPPOPolicy.get_value).
        rewards = np.asarray(self.rewards, dtype=np.float32)  # [T, N]
        values  = np.asarray(self.values, dtype=np.float32)    # [T, N]
        
        # Broadcast each timestep's terminal mask across its agents.
        masks       = np.asarray(self.masks, dtype=np.float32)[:, None]  # [T, 1]
        last_values = np.asarray(last_values, dtype=np.float32)

        advantages  = np.zeros_like(rewards, dtype=np.float32)
        gae         = np.zeros(self.config.num_agents, dtype=np.float32)
        next_values = last_values

        # Accumulate discounted TD residuals backward, separately for each agent.
        for t in reversed(range(len(rewards))):
            # Prediction error: reward plus discounted next-state value minus current value;
            # the mask removes next-state value when this transition ends the episode.
            delta = rewards[t] + self.config.gamma * next_values * masks[t] - values[t]

            # Add discounted future prediction errors; the terminal mask stops the trace.
            gae = delta + self.config.gamma * self.config.gae_lambda * masks[t] * gae

            # Store the accumulated advantage for each agent at this timestep.
            advantages[t] = gae

            # Moving backward, this state's value becomes the next-state value for t - 1.
            next_values = values[t]

        # Add the baseline back to produce critic regression targets.
        returns = advantages + values
        
        return advantages, returns

    def flatten_for_training(
        self,
        advantages: np.ndarray,
        returns:    np.ndarray
    ) -> dict[str, np.ndarray]:
        """Convert [time, agent, ...] rollout data into PPO sample rows."""
        
        # Convert stored local observations to a float32 array indexed by
        # timestep (T), agent (N), and observation component (O).
        observations = np.asarray(self.observations, dtype=np.float32)  # [T,N,O]

        # Convert joint states to float32, with one state vector of S components
        # per timestep; each will later be repeated for the individual agent rows.
        states = np.asarray(self.global_states, dtype=np.float32)       # [T,S]

        # Convert discrete action choices to 64-bit integers, retaining one
        # action index per timestep and agent for PyTorch's action scoring.
        actions = np.asarray(self.actions, dtype=np.int64)              # [T,N]

        # Convert stored action log probabilities to float32; these remain the
        # rollout policy's reference scores when PPO evaluates the updated policy.
        log_probs = np.asarray(self.log_probs, dtype=np.float32)        # [T,N]

        time_steps = observations.shape[0]
        
        # Attach the same global state to every agent row at a given timestep.
        repeated_states = np.repeat(states[:, None, :], self.config.num_agents, axis=1)
        
        # Preserve which critic head belongs to each row after flattening.
        # broadcast_to returns a read-only view; copy it so PyTorch can safely
        # share the resulting array's memory, even for a one-timestep rollout.
        agent_ids = np.broadcast_to(
            np.arange(self.config.num_agents, dtype=np.int64),
            (time_steps, self.config.num_agents),
        ).copy()

        # Flatten in time-major order consistently across inputs and targets.
        return {
            "obs":          observations.reshape(-1, self.config.obs_dim),
            "state":        repeated_states.reshape(-1, self.config.global_state_dim),
            "agent_id":     agent_ids.reshape(-1),
            "action":       actions.reshape(-1),
            "old_log_prob": log_probs.reshape(-1),
            "advantage":    advantages.reshape(-1),
            "return":       returns.reshape(-1),
        }
